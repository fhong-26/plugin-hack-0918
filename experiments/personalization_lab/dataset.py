def registry(ids: list[str]) -> list[dict]:
    result = []
    for route in ids:
        operation, description = CAPABILITIES[route]
        kind = "agent" if route.startswith("agent.") else "native" if route.startswith("native.") else "mcp"
        result.append({"id": route, "kind": kind, "description": description,
                       "operations": [operation], "available": True,
                       "invocation": {"registered_id": route},
                       "input_schema": {"type": "object", "properties": {"query": {"type": "string"}}, "required": ["query"]}})
    return result


def generate(seed: int = 20260918) -> list[dict]:
    rng = random.Random(seed)
    rows = []
    for split, domains in DOMAINS.items():
        for domain in domains:
            for category, template in enumerate(TEMPLATES[split]):
                if category < 2 or category >= 10:
                    ids = ["native.lexical_search", "mcp.semantic_search", "native.filename_search"]
                elif category < 4 or category in (7, 8):
                    ids = ["mcp.docs_search", "mcp.tracker_search"]
                elif category == 6:
                    ids = ["linear.get_issue", "linear.list_comments", "mcp.tracker_search"]
                else:
                    ids = ["agent.reviewer", "agent.test_specialist"]
                operation = CAPABILITIES[ids[0]][0]
                for user, profile in PROFILES.items():
                    goal = template.format(domain=domain)
                    available = registry(ids)
                    rng.shuffle(available)
                    facts = {"domain": domain}
                    if category == 10:
                        facts["exact_symbol"] = "validate_item"
                    if category == 6:
                        facts["issue_id"] = "LAB-" + str(100 + len(rows))
                    packet = {"goal": goal, "operation": operation, "facts": facts,
                              "recent_observations": [], "candidates": [
                                  {key: c[key] for key in ("id", "kind", "description")} for c in available]}
                    target = (profile[operation] if category < 6 else
                              {6: "linear.list_comments", 7: "mcp.docs_search", 8: "mcp.tracker_search",
                               9: "agent.test_specialist", 10: "native.lexical_search", 11: "defer"}[category])
                    acceptable = (["native.lexical_search", "mcp.semantic_search"] if category < 2 else
                                  ids if category < 6 else [target])
                    family = f"{split}/{domain}/{category}"
                    rows.append({"id": digest([family, user])[:16], "family_id": family,
                                 "domain_id": domain, "split": split, "user_id": user,
                                 "kind": "preference" if category < 6 else "rule" if category == 10 else "objective",
                                 "packet": packet, "registry": available, "preferred_route": target,
                                 "acceptable_routes": acceptable, "preferences": preferences(user),
                                 "label_provenance": "synthetic-author-specified-v1"})
    return rows


def write_dataset(path: Path, seed: int = 20260918) -> dict:
    rows = generate(seed)
    path.mkdir(parents=True, exist_ok=False)
    for split in DOMAINS:
        subset = [row for row in rows if row["split"] == split]
        with (path / f"{split}.jsonl").open("w", encoding="utf-8") as stream:
            for row in subset:
                stream.write(json.dumps(row, ensure_ascii=False) + "\n")
    manifest = {"version": 1, "seed": seed, "rows": len(rows), "dataset_digest": digest(rows),
                "splits": {split: sum(r["split"] == split for r in rows) for split in DOMAINS},
                "profiles": {u: preferences(u) for u in PROFILES},
                "provenance": "synthetic; not human user observations", "domains": DOMAINS,
                "test_policy": "No training, hyperparameter selection, or activation on test labels"}
    atomic_json(path / "manifest.json", manifest)
    return manifest


def read_rows(path: Path, split: str) -> list[dict]:
    return [json.loads(line) for line in (path / f"{split}.jsonl").read_text(encoding="utf-8").splitlines() if line]


def training_history(rows: list[dict], user: str) -> list[dict]:
    result = []
    for row in rows:
        if row["split"] != "train":
            raise ValueError("Memory may only use training-history examples")
        if row["user_id"] == user:
            result.append({"decision_id": row["id"], "family_id": row["family_id"], "packet": copy.deepcopy(row["packet"]),
                           "preferred_route": row["preferred_route"], "user_id": user,
                           "source": "synthetic_explicit_correction", "explanation": "Recorded preference for this earlier task."})
    return result
