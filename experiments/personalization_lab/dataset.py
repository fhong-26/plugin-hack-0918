"""Synthetic, declared-preference benchmark with frozen family-level splits.

Labels are author-specified, not generated by the model under evaluation. This
is a synthetic proof-of-mechanism cohort, not evidence of real-user benefit.
"""
from __future__ import annotations

import copy
import json
from pathlib import Path
import random

from rippletide.personalization import atomic_json, digest

CAPABILITIES = {
    "native.lexical_search": ("repository_search", "Find exact text, symbols, error messages or implementation keywords inside source files."),
    "mcp.semantic_search": ("repository_search", "Find code from a natural-language description of its behavior, without an exact symbol."),
    "native.filename_search": ("repository_search", "Find files by a known filename, path, extension or naming pattern."),
    "mcp.docs_search": ("knowledge_lookup", "Search product documentation, published specifications and requirements."),
    "mcp.tracker_search": ("knowledge_lookup", "Search issue reports, approved tickets, reproduction steps and project discussions."),
    "linear.get_issue": ("knowledge_lookup", "Fetch a known issue's title, description and status; does not return its comments."),
    "linear.list_comments": ("knowledge_lookup", "Read the discussion comments attached to a known issue, including clarification replies."),
    "agent.reviewer": ("specialist_assignment", "Review a code patch for correctness, regressions and maintainability; report findings."),
    "agent.test_specialist": ("specialist_assignment", "Design and implement regression tests for a code patch; check boundary cases."),
}

PROFILES = {
    "developer_a": {"repository_search": "native.lexical_search", "knowledge_lookup": "mcp.docs_search", "specialist_assignment": "agent.reviewer"},
    "developer_b": {"repository_search": "mcp.semantic_search", "knowledge_lookup": "mcp.tracker_search", "specialist_assignment": "agent.test_specialist"},
    "developer_c": {"repository_search": "mcp.semantic_search", "knowledge_lookup": "mcp.docs_search", "specialist_assignment": "agent.test_specialist"},
}


def preferences(user: str) -> list[str]:
    profile = PROFILES[user]
    search = "lexical keyword search" if profile["repository_search"] == "native.lexical_search" else "semantic code search"
    lookup = "product documentation" if profile["knowledge_lookup"] == "mcp.docs_search" else "issue tracker"
    specialist = "code reviewer" if profile["specialist_assignment"] == "agent.reviewer" else "test specialist"
    return [f"When either approach is suitable, start with {search} for unfamiliar code.",
            f"When neither source has priority, consult the {lookup} first.",
            f"For an unspecified independent check, choose the {specialist}."]


DOMAINS = {
    "train": ["payment retries", "cart discounts", "cache eviction", "document uploads", "subscription renewal", "inventory reservations"],
    "validation": ["notification delivery", "account recovery"],
    "test": ["session expiration", "background job scheduling"],
}

